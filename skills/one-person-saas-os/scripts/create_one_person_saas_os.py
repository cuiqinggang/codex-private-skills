def ensure_target(root: Path, force: bool) -> None:
    if root.exists() and any(root.iterdir()) and not force:
        raise SystemExit(
            f"Target directory is not empty: {root}\n"
            "Use --force to overwrite generated files in place."
        )
    root.mkdir(parents=True, exist_ok=True)


def init_git(root: Path) -> str:
    try:
        result = subprocess.run(
            ["git", "init"],
            cwd=str(root),
            check=False,
            text=True,
            capture_output=True,
        )
    except FileNotFoundError:
        return "git not found"

    if result.returncode == 0:
        return "initialized"

    return "failed: " + (result.stderr.strip() or result.stdout.strip())


def validate(root: Path) -> tuple[list[str], list[str]]:
    missing = [relative for relative in REQUIRED_PATHS if not (root / relative).exists()]
    forbidden_hits: list[str] = []
    ignored_dirs = {
        ".git",
        ".next",
        "node_modules",
        "dist",
        "build",
        "coverage",
    }
    ignored_files = {
        "package-lock.json",
        "pnpm-lock.yaml",
        "yarn.lock",
    }

    for path in root.rglob("*"):
        if not path.is_file():
            continue
        if path.name in ignored_files:
            continue
        if any(part in ignored_dirs for part in path.parts):
            continue
        text = path.read_text(encoding="utf-8", errors="ignore").lower()
        for marker in FORBIDDEN_MARKERS:
            if marker in text and "forbidden_markers" not in path.name.lower():
                forbidden_hits.append(f"{path.relative_to(root)}:{marker}")

    return missing, forbidden_hits


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, help="Project output directory")
    parser.add_argument("--project-name", help="Package/project name")
    parser.add_argument("--force", action="store_true", help="Overwrite generated files")
    parser.add_argument("--no-git", action="store_true", help="Skip git init")
    args = parser.parse_args()

    root = Path(args.output).expanduser().resolve()
    project_name = args.project_name or normalize_project_name(root)

    ensure_target(root, args.force)

    for relative, content in build_files(project_name).items():
      write_file(root, relative, content)

    git_status = "skipped"
    if not args.no_git:
        git_status = init_git(root)

    missing, forbidden_hits = validate(root)

    print("ONE_PERSON_SAAS_OS_GENERATED")
    print(f"project: {root}")
    print(f"project_name: {project_name}")
    print(f"git: {git_status}")
    print("required_files:")
    for relative in REQUIRED_PATHS:
        status = "OK" if (root / relative).exists() else "MISSING"
        print(f"- {status} {relative}")

    if missing:
        print("status: PARTIAL")
        print("missing: " + ", ".join(missing))
        return 2

    if forbidden_hits:
        print("status: PARTIAL")
        print("forbidden_hits: " + ", ".join(forbidden_hits))
        return 3

    print("status: REVIEW_READY")
    print("next: npm install")
    print("next: npm run build")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
